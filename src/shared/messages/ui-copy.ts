export type UiCopyKey = keyof typeof UI_COPY;

/** Looks up a UI string and fills `{x}` placeholders. A missing variable throws (tests catch it). */
export function uiText(key: UiCopyKey, vars: Record<string, string | number> = {}): string {
  return UI_COPY[key].replace(/\{(\w+)\}/g, (_, name: string) => {
    const value = vars[name];
    if (value === undefined) throw new Error(`Missing "${name}" for ui copy ${key}`);
    return String(value);
  });
}
